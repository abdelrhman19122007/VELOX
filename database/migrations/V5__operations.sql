CREATE TABLE driver_status (
    user_id    BIGINT      PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    online     BOOLEAN     NOT NULL DEFAULT FALSE,
    vehicle    VARCHAR(12) NOT NULL DEFAULT 'MOTORBIKE'
               CHECK (vehicle IN ('MOTORBIKE', 'TUKTUK', 'BICYCLE', 'CAR')),
    lat        DOUBLE PRECISION,
    lng        DOUBLE PRECISION,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE reviews (
    order_id     BIGINT PRIMARY KEY REFERENCES orders (id) ON DELETE CASCADE,
    store_rating INT    NOT NULL CHECK (store_rating BETWEEN 1 AND 5),
    driver_rating INT   CHECK (driver_rating BETWEEN 1 AND 5),
    comment      VARCHAR(1000),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE complaints (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(20)   NOT NULL UNIQUE,
    order_id          BIGINT        NOT NULL REFERENCES orders (id),
    details           VARCHAR(1000) NOT NULL,
    status            VARCHAR(10)   NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'CLOSED')),
    compensation_code VARCHAR(20),
    admin_note        VARCHAR(500),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at         TIMESTAMP WITH TIME ZONE
);
CREATE INDEX complaints_status ON complaints (status);

-- In-app notification inbox (push notifications are also sent to push_devices).
CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      VARCHAR(120) NOT NULL,
    body       VARCHAR(300) NOT NULL,
    order_id   BIGINT       REFERENCES orders (id) ON DELETE SET NULL,
    read       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX notifications_user ON notifications (user_id, read);
