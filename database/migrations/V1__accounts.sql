CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     VARCHAR(20)  NOT NULL UNIQUE,              -- the id the API exposes (never the numeric id)
    email         VARCHAR(120) NOT NULL UNIQUE,
    name          VARCHAR(60)  NOT NULL,
    phone         VARCHAR(20),
    picture       VARCHAR(400),
    provider      VARCHAR(20)  NOT NULL DEFAULT 'password',  -- password / google / seed
    role          VARCHAR(12)  NOT NULL DEFAULT 'CUSTOMER'
                  CHECK (role IN ('CUSTOMER', 'RESTAURANT', 'DRIVER', 'ADMIN')),
    store_id      VARCHAR(10),                               -- RESTAURANT accounts (FK added in V2)
    password_hash VARCHAR(200),                              -- PBKDF2-SHA256, never plain text
    token_version INT          NOT NULL DEFAULT 0,           -- +1 = every session of this account ends
    blocked       BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX users_role ON users (role);

-- Saved delivery addresses. In Samannoud people describe places by landmarks, not street numbers.
CREATE TABLE addresses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label      VARCHAR(30)  NOT NULL,                        -- Home, Work, Mom's house…
    zone       VARCHAR(30)  NOT NULL,                        -- delivery_zones.code (FK added in V3)
    address    VARCHAR(300) NOT NULL,
    landmark   VARCHAR(150),                                 -- "next to the big mosque"
    phone      VARCHAR(20)  NOT NULL,
    lat        DOUBLE PRECISION CHECK (lat BETWEEN -90 AND 90),
    lng        DOUBLE PRECISION CHECK (lng BETWEEN -180 AND 180),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX addresses_user ON addresses (user_id);

-- Phones / browsers that receive push notifications (Firebase Cloud Messaging tokens).
CREATE TABLE push_devices (
    token      VARCHAR(400) PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    platform   VARCHAR(10)  NOT NULL CHECK (platform IN ('web', 'android', 'ios')),
    lang       VARCHAR(5)   NOT NULL DEFAULT 'ar',
    origin     VARCHAR(200),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX push_devices_user ON push_devices (user_id);

-- Every sign-in try (security: brute-force detection and the evidence for the pentest report).
CREATE TABLE login_attempts (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email   VARCHAR(120) NOT NULL,
    ip      VARCHAR(45),
    success BOOLEAN      NOT NULL,
    at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX login_attempts_email_at ON login_attempts (email, at);
CREATE INDEX login_attempts_ip_at ON login_attempts (ip, at);

-- Sensitive actions: who did what, when, from where (block user, reset password, cancel order, refund…).
CREATE TABLE audit_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id  BIGINT       REFERENCES users (id) ON DELETE SET NULL,
    action    VARCHAR(40)  NOT NULL,
    entity    VARCHAR(30)  NOT NULL,
    entity_id VARCHAR(40),
    ip        VARCHAR(45),
    details   VARCHAR(1000),
    at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX audit_log_at ON audit_log (at);
CREATE INDEX audit_log_actor ON audit_log (actor_id);
