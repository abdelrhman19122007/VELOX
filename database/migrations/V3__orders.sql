-- Samannoud areas and the villages around it, each with a fixed delivery fee (managed by the admin).
CREATE TABLE delivery_zones (
    code      VARCHAR(30)    PRIMARY KEY,
    name_ar   VARCHAR(60)    NOT NULL,
    name_en   VARCHAR(60)    NOT NULL,
    kind      VARCHAR(10)    NOT NULL CHECK (kind IN ('CITY', 'VILLAGE')),
    fee       NUMERIC(8, 2)  NOT NULL CHECK (fee >= 0),
    eta_min   INT            NOT NULL DEFAULT 30,             -- usual minutes to deliver there
    active    BOOLEAN        NOT NULL DEFAULT TRUE,
    sort_order INT           NOT NULL DEFAULT 0
);

ALTER TABLE addresses ADD CONSTRAINT addresses_zone FOREIGN KEY (zone) REFERENCES delivery_zones (code);

CREATE SEQUENCE order_code_seq START WITH 1001;

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)    NOT NULL UNIQUE,            -- ORD-1001 (what people see)
    kind           VARCHAR(10)    NOT NULL DEFAULT 'STORE'
                   CHECK (kind IN ('STORE', 'ERRAND')),       -- ERRAND = "bring me anything"
    customer_id    BIGINT         NOT NULL REFERENCES users (id),
    store_id       VARCHAR(10)    REFERENCES stores (id),     -- null for errands
    driver_id      BIGINT         REFERENCES users (id),
    status         VARCHAR(16)    NOT NULL
                   CHECK (status IN ('PENDING_PAYMENT', 'PLACED', 'ACCEPTED', 'READY', 'PICKED_UP',
                                     'DELIVERED', 'REJECTED', 'CANCELLED', 'RETURNED')),
    zone           VARCHAR(30)    NOT NULL REFERENCES delivery_zones (code),
    phone          VARCHAR(20)    NOT NULL,
    address        VARCHAR(300)   NOT NULL,
    landmark       VARCHAR(150),
    lat            DOUBLE PRECISION,
    lng            DOUBLE PRECISION,
    errand_details VARCHAR(1000),                             -- what to buy, for errands
    subtotal       NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
    discount       NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    delivery_fee   NUMERIC(12, 2) NOT NULL CHECK (delivery_fee >= 0),
    packaging_fee  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    total          NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
    cash_change_for NUMERIC(12, 2),                           -- "I'll pay with 200" → driver brings change
    payment_method VARCHAR(16)    NOT NULL DEFAULT 'CASH'
                   CHECK (payment_method IN ('CASH', 'VODAFONE_CASH', 'FAWRY', 'WALLET')),
    payment_status VARCHAR(16)    NOT NULL DEFAULT 'COD'
                   CHECK (payment_status IN ('COD', 'PENDING', 'PAID', 'REFUNDED', 'EXPIRED')),
    promo          VARCHAR(20),
    reject_reason  VARCHAR(200),
    scheduled_for  TIMESTAMP WITH TIME ZONE,                  -- e.g. iftar time in Ramadan
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (kind = 'ERRAND' OR store_id IS NOT NULL)
);
CREATE INDEX orders_customer ON orders (customer_id);
CREATE INDEX orders_store_status ON orders (store_id, status);
CREATE INDEX orders_driver ON orders (driver_id);
CREATE INDEX orders_status_updated ON orders (status, updated_at);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id VARCHAR(10)    NOT NULL,
    name       VARCHAR(120)   NOT NULL,                       -- copied: the receipt never changes
    name_ar    VARCHAR(120)   NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    qty        INT            NOT NULL CHECK (qty BETWEEN 1 AND 99),
    note       VARCHAR(200)                                   -- "no onions"
);
CREATE INDEX order_items_order ON order_items (order_id);

-- Photos attached to an order: pharmacy prescriptions, errand shopping lists.
CREATE TABLE order_attachments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    kind       VARCHAR(16)  NOT NULL CHECK (kind IN ('PRESCRIPTION', 'LIST', 'PHOTO')),
    url        VARCHAR(400) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Every status change: the order timeline and the audit trail of who moved it.
CREATE TABLE order_events (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    status   VARCHAR(16) NOT NULL,
    actor_id BIGINT      REFERENCES users (id),
    at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX order_events_order ON order_events (order_id);
