-- =====================================================================

-- One row per payment attempt or refund (orders keeps only the current summary).
CREATE TABLE payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    method      VARCHAR(16)    NOT NULL CHECK (method IN ('CASH', 'VODAFONE_CASH', 'FAWRY', 'WALLET')),
    kind        VARCHAR(10)    NOT NULL DEFAULT 'CHARGE' CHECK (kind IN ('CHARGE', 'REFUND')),
    amount      NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    status      VARCHAR(12)    NOT NULL CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'EXPIRED', 'REFUNDED')),
    reference   VARCHAR(40),                                  -- Fawry reference / wallet transaction id
    wallet_phone VARCHAR(20),
    code_hash   VARCHAR(200),                                 -- Vodafone Cash confirmation code, hashed
    attempts    INT            NOT NULL DEFAULT 0,
    expires_at  TIMESTAMP WITH TIME ZONE,
    paid_at     TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX payments_order ON payments (order_id);
CREATE INDEX payments_pending ON payments (status, expires_at);
CREATE UNIQUE INDEX payments_reference ON payments (reference) WHERE reference IS NOT NULL;

-- In-app wallet: balance = SUM(amount). Credits are positive, spending negative.
CREATE TABLE wallet_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    amount     NUMERIC(12, 2) NOT NULL CHECK (amount <> 0),
    reason     VARCHAR(20)    NOT NULL CHECK (reason IN ('TOP_UP', 'ORDER', 'REFUND', 'COMPENSATION', 'LOYALTY')),
    order_id   BIGINT         REFERENCES orders (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX wallet_user ON wallet_transactions (user_id);

CREATE TABLE promo_codes (
    code        VARCHAR(20)   PRIMARY KEY,
    kind        VARCHAR(16)   NOT NULL CHECK (kind IN ('PERCENT', 'FIXED', 'FREE_DELIVERY')),
    value       NUMERIC(8, 2) NOT NULL DEFAULT 0,
    min_order   NUMERIC(8, 2) NOT NULL DEFAULT 0,
    user_id     BIGINT        REFERENCES users (id),          -- null = for everyone
    max_uses    INT,                                          -- null = unlimited
    used_count  INT           NOT NULL DEFAULT 0,
    expires_at  TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Loyalty points: earned per delivered order, spent as a discount.
CREATE TABLE loyalty_points (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    points     INT         NOT NULL CHECK (points <> 0),
    order_id   BIGINT      REFERENCES orders (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX loyalty_user ON loyalty_points (user_id);
